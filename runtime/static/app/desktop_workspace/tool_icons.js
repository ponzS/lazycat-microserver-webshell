export function desktopToolIcon(command) {
  const name = command.toLowerCase().replace(/\.(exe|cmd|bat)$/, "");
  if (/^python(?:w)?\d+(?:\.\d+)*$/.test(name)) return commandIcons.get("python");
  if (/^pip\d+(?:\.\d+)*$/.test(name)) return commandIcons.get("pip");
  return commandIcons.get(name) || "";
}
